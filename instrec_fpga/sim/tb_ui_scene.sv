// tb_ui_scene.sv - UI Scene ABI v0 double-bank renderer testbench.
//
// Drives the CPU write port of ui_scene_top through two complete scenes
// (scene A: 3 TEXT + 1 BAR 50%; scene B: 2 TEXT + 2 BAR + 1 RECT) and
// checks, against Python-generated reference frames
// (experiments/ui_scene/gen_expected_frames.py):
//
//   1. bank isolation: while the back bank is being written the scanned
//      output stays pixel-identical to the previous (old) scene frame;
//   2. atomic commit: after COMMIT the frame following the next vsync
//      rising edge renders the new scene exactly (all 640x360 pixels);
//   3. the two scene frames really differ (non-zero pixel diff);
//   4. the COMMIT/ACK handshake completes (commit_ack polling).
//
// Scene data itself comes from the generated hex tables, so the DUT and
// the reference model always see identical descriptors and glyph ids.
`timescale 1ns/1ps

module tb_ui_scene;
    localparam integer FRAME_PIXELS = 640 * 360;

    reg clk = 1'b0;
    always #5 clk = ~clk;

    reg rst_n = 1'b0;
    reg [11:0] wr_addr = 12'h0;
    reg [31:0] wr_data = 32'h0;
    reg [3:0]  wr_be = 4'h0;
    reg        wr_en = 1'b0;

    wire [23:0] rgb;
    wire de_out, hs_out, vs_out;
    wire commit_ack, active_bank;

    ui_scene_top dut (
        .clk        (clk),
        .rst_n      (rst_n),
        .wr_addr    (wr_addr),
        .wr_data    (wr_data),
        .wr_be      (wr_be),
        .wr_en      (wr_en),
        .commit_ack (commit_ack),
        .active_bank(active_bank),
        .rgb        (rgb),
        .de_out     (de_out),
        .hs_out     (hs_out),
        .vs_out     (vs_out)
    );

    // ------------------------------------------------------------------
    // Reference data (generated by experiments/ui_scene/gen_expected_frames.py)
    // ------------------------------------------------------------------
    reg [31:0] frame_init [0:FRAME_PIXELS-1];
    reg [31:0] frame_a    [0:FRAME_PIXELS-1];
    reg [31:0] frame_b    [0:FRAME_PIXELS-1];
    reg [31:0] scene_a_desc [0:255];
    reg [31:0] scene_b_desc [0:255];
    reg [7:0]  scene_a_glyph [0:511];
    reg [7:0]  scene_b_glyph [0:511];

    reg [31:0] cap_buf [0:FRAME_PIXELS-1];
    integer cap_n;

    integer errors = 0;

    initial begin
        $readmemh("build/sim/ui_scene/frame_init.hex", frame_init);
        $readmemh("build/sim/ui_scene/frame_a.hex", frame_a);
        $readmemh("build/sim/ui_scene/frame_b.hex", frame_b);
        $readmemh("build/sim/ui_scene/scene_a_desc.hex", scene_a_desc);
        $readmemh("build/sim/ui_scene/scene_b_desc.hex", scene_b_desc);
        $readmemh("build/sim/ui_scene/scene_a_glyph.hex", scene_a_glyph);
        $readmemh("build/sim/ui_scene/scene_b_glyph.hex", scene_b_glyph);
    end

    // ------------------------------------------------------------------
    // CPU write helpers (driven on the negative edge, one word per task call)
    // ------------------------------------------------------------------
    task automatic cpu_write(input [11:0] a, input [31:0] d, input [3:0] be);
        begin
            @(negedge clk);
            wr_addr = a;
            wr_data = d;
            wr_be = be;
            wr_en = 1'b1;
            @(negedge clk);
            wr_en = 1'b0;
        end
    endtask

    // which = 0: scene A descriptors + glyph ids (256 words + 512 bytes)
    // which = 1: scene B
    task automatic write_scene(input integer which);
        integer i;
        begin
            for (i = 0; i < 256; i = i + 1) begin
                if (which == 0)
                    cpu_write(i[11:0], scene_a_desc[i], 4'hF);
                else
                    cpu_write(i[11:0], scene_b_desc[i], 4'hF);
            end
            for (i = 0; i < 512; i = i + 1) begin
                if (which == 0)
                    cpu_write(12'h200 + i[11:0], {24'd0, scene_a_glyph[i]}, 4'h1);
                else
                    cpu_write(12'h200 + i[11:0], {24'd0, scene_b_glyph[i]}, 4'h1);
            end
        end
    endtask

    // ------------------------------------------------------------------
    // Frame capture: start at the next vs_out rising edge, then collect
    // exactly FRAME_PIXELS de-qualified pixels in scan order.
    // ------------------------------------------------------------------
    task automatic capture_frame;
        begin
            @(posedge vs_out);
            cap_n = 0;
            while (cap_n < FRAME_PIXELS) begin
                @(posedge clk);
                #1;
                if (de_out) begin
                    cap_buf[cap_n] = rgb;
                    cap_n = cap_n + 1;
                end
            end
        end
    endtask

    // ------------------------------------------------------------------
    // Frame comparison: exp_sel 0 = frame_init, 1 = frame_a, 2 = frame_b.
    // ------------------------------------------------------------------
    function [31:0] exp_pixel(input integer exp_sel, input integer idx);
        begin
            case (exp_sel)
                0: exp_pixel = frame_init[idx];
                1: exp_pixel = frame_a[idx];
                default: exp_pixel = frame_b[idx];
            endcase
        end
    endfunction

    task automatic check_frame(input integer exp_sel,
                               input [8*24-1:0] label,
                               output integer mismatch);
        integer i;
        begin
            mismatch = 0;
            for (i = 0; i < FRAME_PIXELS; i = i + 1) begin
                if (cap_buf[i] !== exp_pixel(exp_sel, i)) begin
                    if (mismatch == 0)
                        $display("FIRST_MISMATCH %s px=%0d got=%h exp=%h",
                                 label, i, cap_buf[i], exp_pixel(exp_sel, i));
                    mismatch = mismatch + 1;
                end
            end
        end
    endtask

    // ------------------------------------------------------------------
    // Commit handshake with a bounded wait (one frame period is 324000
    // cycles; allow some margin).
    // ------------------------------------------------------------------
    task automatic commit_and_wait(output integer ok);
        integer t;
        begin
            cpu_write(12'h100, 32'h1, 4'hF);
            t = 0;
            ok = 1;
            while (commit_ack !== 1'b1 && t < 400000) begin
                @(posedge clk);
                t = t + 1;
            end
            if (commit_ack !== 1'b1) begin
                $display("ERROR: commit_ack timeout (%0d cycles)", t);
                ok = 0;
            end
        end
    endtask

    integer mm, ok, diff_cnt, i;
    integer scene1_fail, scene2_fail;

    initial begin
        scene1_fail = 0;
        scene2_fail = 0;

        repeat (10) @(negedge clk);
        rst_n = 1'b1;

        // Wait for one full frame so the prefetch settles on the reset
        // (all-HIDDEN) bank 0 content.
        capture_frame;

        // ----------------------------------------------------------
        // SCENE 1: write scene A into the back bank while a frame is
        // being scanned; the captured frame must stay black.
        // ----------------------------------------------------------
        fork
            write_scene(0);
            capture_frame;
        join
        check_frame(0, "scene1_write_isolation", mm);
        if (mm != 0) begin
            scene1_fail = scene1_fail + 1;
            $display("SCENE 1 FAIL write-isolation mismatch=%0d (expected black frame)", mm);
        end else begin
            $display("SCENE 1: write-isolation PASS (%0d pixels black while back bank is written)", FRAME_PIXELS);
        end

        // COMMIT scene A; the frame after the next frame boundary must
        // match reference frame A pixel by pixel.
        commit_and_wait(ok);
        if (ok != 1) scene1_fail = scene1_fail + 1;
        capture_frame;
        check_frame(1, "scene1_commit", mm);
        if (mm != 0) begin
            scene1_fail = scene1_fail + 1;
            $display("SCENE 1 FAIL commit mismatch=%0d vs frame_a", mm);
        end else begin
            $display("SCENE 1: commit-switch PASS (%0d pixels match frame_a)", FRAME_PIXELS);
        end

        // ----------------------------------------------------------
        // SCENE 2: write scene B into the other back bank; while it is
        // written the scanned frame must stay identical to scene A.
        // ----------------------------------------------------------
        fork
            write_scene(1);
            capture_frame;
        join
        check_frame(1, "scene2_write_isolation", mm);
        if (mm != 0) begin
            scene2_fail = scene2_fail + 1;
            $display("SCENE 2 FAIL write-isolation mismatch=%0d (expected frame_a)", mm);
        end else begin
            $display("SCENE 2: write-isolation PASS (%0d pixels still frame_a while back bank is written)", FRAME_PIXELS);
        end

        // COMMIT scene B and compare against reference frame B.
        commit_and_wait(ok);
        if (ok != 1) scene2_fail = scene2_fail + 1;
        capture_frame;
        check_frame(2, "scene2_commit", mm);
        if (mm != 0) begin
            scene2_fail = scene2_fail + 1;
            $display("SCENE 2 FAIL commit mismatch=%0d vs frame_b", mm);
        end else begin
            $display("SCENE 2: commit-switch PASS (%0d pixels match frame_b)", FRAME_PIXELS);
        end

        // ----------------------------------------------------------
        // Layout change: the two reference frames must differ.
        // ----------------------------------------------------------
        diff_cnt = 0;
        for (i = 0; i < FRAME_PIXELS; i = i + 1)
            if (frame_a[i] !== frame_b[i]) diff_cnt = diff_cnt + 1;
        if (diff_cnt == 0) begin
            errors = errors + 1;
            $display("SCENE 2 FAIL sceneA and sceneB frames are identical");
        end else begin
            $display("FRAME-DIFF sceneA vs sceneB: %0d pixels differ (non-zero: OK)", diff_cnt);
        end

        if (scene1_fail == 0)
            $display("SCENE 1 PASS");
        else
            $display("SCENE 1 FAIL (%0d sub-checks failed)", scene1_fail);
        if (scene2_fail == 0)
            $display("SCENE 2 PASS");
        else
            $display("SCENE 2 FAIL (%0d sub-checks failed)", scene2_fail);

        errors = errors + scene1_fail + scene2_fail;
        if (errors == 0) begin
            $display("TB_UI_SCENE: PASS");
            $display("RESULT: PASS scenes=2 frames_checked=4 pixels=%0d",
                     4 * FRAME_PIXELS);
        end else begin
            $display("TB_UI_SCENE: FAIL errors=%0d", errors);
            $display("RESULT: FAIL errors=%0d", errors);
        end
        $finish;
    end

endmodule
