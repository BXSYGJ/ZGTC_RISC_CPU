def cjk(char):
    return ord(char) > 127


def generated_functions(glyphs):
    lines = ["    // Generated by gen_assets.py; glyph zero is transparent space.",
             f"    localparam [7:0] GLYPH_ZERO = 8'd{glyphs['0']};",
             f"    localparam [7:0] GLYPH_PERCENT = 8'd{glyphs['%']};",
             f"    localparam [7:0] GLYPH_DASH = 8'd{glyphs['-']};",
             "    function [7:0] label_glyph;", "        input [3:0] label_id;",
             "        input [3:0] character;", "        begin", "            case ({label_id,character})"]
    for label_id, label in enumerate(LABELS):
        for position, char in enumerate(label):
            lines.append(f"                8'h{label_id * 16 + position:02x}: label_glyph = 8'd{glyphs[char]};")
    lines += ["                default: label_glyph = 8'd0;", "            endcase", "        end", "    endfunction"]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/msyh.ttc"))
    parser.add_argument("--latin-font", type=Path, default=Path("C:/Windows/Fonts/segoeui.ttf"))
    args = parser.parse_args()
    for filename in [args.font, args.latin_font]:
        if not filename.is_file():
            parser.error(f"Font does not exist: {filename}")
    characters = set("0123456789%-" + "".join(LABELS))
    for entries in PAGES.values():
        characters.update("".join(entry[2] for entry in entries))
    ordered = list(" 0123456789") + sorted(characters - set(" 0123456789"))
    if len(ordered) > 256:
        raise ValueError(f"Font budget exceeded: {len(ordered)} glyphs")
    glyphs = {char: index for index, char in enumerate(ordered)}
    chinese = ImageFont.truetype(str(args.font), 28)
    latin = ImageFont.truetype(str(args.latin_font), 26)
    font = [0] * 8192
    for char, index in glyphs.items():
        if char == " ":
            continue
        width = 32 if cjk(char) else 16
        image = Image.new("L", (width, 32), 0)
        draw = ImageDraw.Draw(image)
        chosen = chinese if cjk(char) else latin
        left, top, right, bottom = draw.textbbox((0, 0), char, font=chosen)
        draw.text(((width - (right - left)) / 2 - left, (32 - (bottom - top)) / 2 - top), char, font=chosen, fill=255)
        if width != 16:
            image = image.resize((16, 32), Image.Resampling.LANCZOS)
        for y in range(32):
            word = 0
            for x in range(16):
                word = (word << 1) | (image.getpixel((x, y)) >= 96)
            font[index * 32 + y] = word
    assets = ROOT / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    (assets / "symphony_font.hex").write_text("".join(f"{word:04x}\n" for word in font), encoding="ascii")
    for name, entries in PAGES.items():
        tiles = [0] * 4096
        for x, y, value, color, large in entries:
            column, row = x // 16, y // 32
            for char in value:
                scale = (3 if cjk(char) else 2) if large else (1 if cjk(char) else 0)
                columns = [1, 2, 2, 4][scale]
                rows = 2 if large else 1
                if column + columns > 120 or row + rows > 34:
                    raise ValueError(f"Text outside screen: {name} {value}")
                for dy in range(rows):
                    for dx in range(columns):
                        address = (row + dy) * 120 + column + dx
                        if tiles[address]:
                            raise ValueError(f"Overlapping text: {name} {value} at {address}")
                        tiles[address] = glyphs[char] | (color << 8) | (scale << 11) | (dx << 13) | (dy << 15)
                column += columns
        (assets / f"symphony_{name}.hex").write_text("".join(f"{word:04x}\n" for word in tiles), encoding="ascii")
    functions = generated_functions(glyphs)
    renderer = ROOT / "symphony_renderer.v"
    if renderer.is_file():
        source = renderer.read_text(encoding="ascii")
        begin, end = "    // ASSETS_BEGIN", "    // ASSETS_END"
        if begin not in source or end not in source:
            raise ValueError("Renderer asset markers are missing")
        source = source.split(begin)[0] + begin + "\n" + functions + "\n" + end + source.split(end, 1)[1]
        renderer.write_text(source, encoding="ascii", newline="\n")
    manifest = {"glyph_count": len(ordered), "font_bytes": 16384, "tile_bytes_per_page": 8192,
                "font_sha256": hashlib.sha256(args.font.read_bytes()).hexdigest(),
                "latin_font_sha256": hashlib.sha256(args.latin_font.read_bytes()).hexdigest(),
                "glyphs": glyphs, "class_order": CLASSES,
                "assets": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in assets.glob("*.hex")}}
    (assets / "ASSETS.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"SYMPHONY_ASSETS_PASS glyphs={len(ordered)} font_bytes=16384 tile_pages=2 tile_bytes=16384")


if __name__ == "__main__":
    main()
