// symphony_renderer: native 1080p instrument guide and bounded result library.
// Font, geometry, and video timing share exactly five pixel-clock stages.
module symphony_renderer #(
    parameter SIMULATION = 0,
    parameter FONT_HEX = "src/ui/symphony_font.hex",
    parameter GUIDE_HEX = "src/ui/symphony_guide.hex",
    parameter LIBRARY_HEX = "src/ui/symphony_library.hex"
) (
    input wire pix_clk, rst_pix_n,
    input wire [10:0] pix_x, pix_y,
    input wire pix_de, pix_hs, pix_vs,
    output wire [10:0] wave_rd_addr,
    input wire [15:0] wave_min, wave_max,
    input wire wave_valid, mute_flag_sync,
    output wire [14:0] spec_ram_addr,
    input wire [7:0] spec_ram_data,
    input wire feature_ready, result_ready,
    input wire [3:0] class_idx,
    input wire [7:0] pct0, pct1, pct2, pct3, pct4, pct5, pct6, pct7,
    input wire page_library,
    input wire [3:0] filter_class,
    input wire [5:0] selected_index,
    input wire [6:0] item_count, history_count,
    input wire [31:0] result_time_ms, result_sequence,
    output wire [5:0] rd_index,
    output wire rd_all,
    input wire rd_valid,
    input wire [2:0] rd_class,
    input wire [7:0] rd_confidence,
    input wire [31:0] rd_time_ms, rd_sequence,
    input wire rd_bookmark,
    input wire selected_valid,
    input wire [2:0] selected_class,
    input wire [7:0] selected_confidence,
    input wire [31:0] selected_time_ms, selected_sequence,
    input wire selected_bookmark,
    output wire vsync_pulse,
    output reg [23:0] rgb,
    output wire de_out, hs_out, vs_out
);
    localparam [23:0] IVORY = 24'hf4f6ef;
    localparam [23:0] INK = 24'h244a36;
    localparam [23:0] MUTED = 24'h7d9076;
    localparam [23:0] SIDEBAR = 24'h18332e;
    reg [15:0] font_rom [0:8191];
    reg [15:0] guide_rom [0:4095];
    reg [15:0] library_rom [0:4095];
    initial begin
        $readmemh(FONT_HEX, font_rom);
        $readmemh(GUIDE_HEX, guide_rom);
        $readmemh(LIBRARY_HEX, library_rom);
    end

    // ASSETS_BEGIN
    // Generated by gen_assets.py; glyph zero is transparent space.
    localparam [7:0] GLYPH_ZERO = 8'd1;
    localparam [7:0] GLYPH_PERCENT = 8'd11;
    localparam [7:0] GLYPH_DASH = 8'd12;
    function [7:0] label_glyph;
        input [3:0] label_id;
        input [3:0] character;
        begin
            case ({label_id,character})
                8'h00: label_glyph = 8'd62;
                8'h01: label_glyph = 8'd130;
                8'h02: label_glyph = 8'd129;
                8'h10: label_glyph = 8'd75;
                8'h11: label_glyph = 8'd120;
                8'h12: label_glyph = 8'd117;
                8'h13: label_glyph = 8'd67;
                8'h14: label_glyph = 8'd48;
                8'h20: label_glyph = 8'd76;
                8'h21: label_glyph = 8'd74;
                8'h30: label_glyph = 8'd150;
                8'h31: label_glyph = 8'd126;
                8'h40: label_glyph = 8'd149;
                8'h41: label_glyph = 8'd116;
                8'h50: label_glyph = 8'd112;
                8'h51: label_glyph = 8'd45;
                8'h52: label_glyph = 8'd153;
                8'h53: label_glyph = 8'd137;
                8'h54: label_glyph = 8'd51;
                8'h55: label_glyph = 8'd96;
                8'h60: label_glyph = 8'd80;
                8'h61: label_glyph = 8'd66;
                8'h70: label_glyph = 8'd80;
                8'h71: label_glyph = 8'd93;
                8'h72: label_glyph = 8'd116;
                8'h80: label_glyph = 8'd127;
                8'h81: label_glyph = 8'd86;
                8'h82: label_glyph = 8'd134;
                8'h83: label_glyph = 8'd107;
                8'h90: label_glyph = 8'd82;
                8'h91: label_glyph = 8'd94;
                8'h92: label_glyph = 8'd138;
                8'ha0: label_glyph = 8'd104;
                8'ha1: label_glyph = 8'd94;
                8'ha2: label_glyph = 8'd138;
                8'hb0: label_glyph = 8'd52;
                8'hb1: label_glyph = 8'd147;
                8'hc0: label_glyph = 8'd101;
                8'hc1: label_glyph = 8'd98;
                8'hc2: label_glyph = 8'd134;
                8'hc3: label_glyph = 8'd107;
                default: label_glyph = 8'd0;
            endcase
        end
    endfunction
    // ASSETS_END

    function [23:0] class_color;
        input [2:0] category;
        begin
            case (category)
                0: class_color = 24'h75b79d;
                1: class_color = 24'hb393c8;
                2: class_color = 24'hd9a0b5;
                3: class_color = 24'h87b7c8;
                4: class_color = 24'he0bc73;
                5: class_color = 24'hbdaf76;
                6: class_color = 24'hd99572;
                default: class_color = 24'h9aaad1;
            endcase
        end
    endfunction
    function [23:0] text_color;
        input [2:0] color;
        begin
            case (color)
                1: text_color = MUTED;
                2: text_color = 24'hf0f6ea;
                3: text_color = 24'ha6c6b4;
                default: text_color = INK;
            endcase
        end
    endfunction
    function [10:0] chip_left;
        input [3:0] category;
        begin
            case (category)
                0: chip_left=464; 1: chip_left=608; 2: chip_left=848;
                3: chip_left=960; 4: chip_left=1072; 5: chip_left=1184;
                6: chip_left=1456; 7: chip_left=1568;
                default: chip_left=352;
            endcase
        end
    endfunction
    function [10:0] chip_right;
        input [3:0] category;
        begin
            case (category)
                0: chip_right=592; 1: chip_right=832; 2: chip_right=944;
                3: chip_right=1056; 4: chip_right=1168; 5: chip_right=1440;
                6: chip_right=1552; 7: chip_right=1696;
                default: chip_right=448;
            endcase
        end
    endfunction
    function [7:0] decimal_glyph;
        input [7:0] value;
        input [1:0] position;
        reg [7:0] bounded;
        begin
            bounded = value > 100 ? 100 : value;
            case (position)
                0: decimal_glyph = bounded == 100 ? GLYPH_ZERO+1'b1 : 8'd0;
                1: decimal_glyph = bounded < 10 ? 8'd0 : GLYPH_ZERO + (bounded == 100 ? 0 : bounded/10);
                2: decimal_glyph = GLYPH_ZERO + bounded%10;
                default: decimal_glyph = GLYPH_PERCENT;
            endcase
        end
    endfunction
    function [7:0] number_glyph;
        input [39:0] value;
        input [3:0] position;
        begin
            case(position)
                0:number_glyph=value[39:36]==0?0:GLYPH_ZERO+value[39:36];
                1:number_glyph=value[39:32]==0?0:GLYPH_ZERO+value[35:32];
                2:number_glyph=value[39:28]==0?0:GLYPH_ZERO+value[31:28];
                3:number_glyph=value[39:24]==0?0:GLYPH_ZERO+value[27:24];
                4:number_glyph=value[39:20]==0?0:GLYPH_ZERO+value[23:20];
                5:number_glyph=value[39:16]==0?0:GLYPH_ZERO+value[19:16];
                6:number_glyph=value[39:12]==0?0:GLYPH_ZERO+value[15:12];
                7:number_glyph=value[39:8]==0?0:GLYPH_ZERO+value[11:8];
                8:number_glyph=value[39:4]==0?0:GLYPH_ZERO+value[7:4];
                default:number_glyph=GLYPH_ZERO+value[3:0];
            endcase
        end
    endfunction

    wire [63:0] percentages = {pct7,pct6,pct5,pct4,pct3,pct2,pct1,pct0};
    wire [2:0] library_row = pix_y >= 448 && pix_y < 960 ? (pix_y-11'd448)>>6 : 3'd0;
    wire [5:0] history_column = (pix_x-11'd400)>>4;
    assign rd_index = page_library ? {selected_index[5:3],library_row} :
                      (pix_x >= 400 && pix_x < 1424 ? 6'd63-history_column : 6'd0);
    assign rd_all = !page_library;
    assign wave_rd_addr = 11'd0;
    assign spec_ram_addr = 15'd0;
    wire [12:0] tile_offset = ({7'd0,pix_y[10:5]}<<7)-({7'd0,pix_y[10:5]}<<3)+{6'd0,pix_x[10:4]};
    wire [11:0] tile_address = pix_de ? tile_offset[11:0] : 12'd0;
    reg [15:0] guide_q, library_q;
    reg [10:0] x_s1, y_s1;
    reg page_s1, ready_s1;
    reg [3:0] class_s1;
    reg [63:0] percentages_s1;
    reg [5:0] selected_s1;
    reg [3:0] filter_s1;
    reg [6:0] item_count_s1;
    reg [4:0] de_pipe, hs_pipe, vs_pipe;
    reg vs_d;
    assign de_out = de_pipe[4];
    assign hs_out = hs_pipe[4];
    assign vs_out = vs_pipe[4];
    assign vsync_pulse = pix_vs && !vs_d;

    // Decimal conversion runs during the left blank/sidebar pixels. Every
    // library row presents its query at x=0, at least 384 clocks before text.
    wire [31:0] target_sequence = page_library ? rd_sequence : result_sequence;
    wire [31:0] target_time = page_library ? rd_time_ms : result_time_ms;
    reg [31:0] cached_sequence, cached_time, sequence_binary, time_binary;
    reg [39:0] sequence_work, time_work, sequence_bcd, time_bcd;
    reg [39:0] sequence_adjusted, time_adjusted;
    reg [5:0] decimal_step;
    reg decimal_busy;
    integer digit;
    always @* begin
        sequence_adjusted=sequence_work;
        time_adjusted=time_work;
        for (digit=0;digit<10;digit=digit+1) begin
            if (sequence_work[digit*4+:4]>=5)
                sequence_adjusted[digit*4+:4]=sequence_work[digit*4+:4]+4'd3;
            if (time_work[digit*4+:4]>=5)
                time_adjusted[digit*4+:4]=time_work[digit*4+:4]+4'd3;
        end
    end
    always @(posedge pix_clk) begin
        if (!rst_pix_n) begin
            cached_sequence<=32'hffffffff;cached_time<=32'hffffffff;
            sequence_binary<=0;time_binary<=0;sequence_work<=0;time_work<=0;
            sequence_bcd<=0;time_bcd<=0;decimal_step<=0;decimal_busy<=0;
        end else if (!decimal_busy) begin
            if (cached_sequence!=target_sequence || cached_time!=target_time) begin
                cached_sequence<=target_sequence;cached_time<=target_time;
                sequence_binary<=target_sequence;time_binary<=target_time;
                sequence_work<=0;time_work<=0;decimal_step<=0;decimal_busy<=1;
            end
        end else begin
            sequence_work<={sequence_adjusted[38:0],sequence_binary[31]};
            time_work<={time_adjusted[38:0],time_binary[31]};
            sequence_binary<={sequence_binary[30:0],1'b0};
            time_binary<={time_binary[30:0],1'b0};
            decimal_step<=decimal_step+1'b1;
            if (decimal_step==31) begin
                sequence_bcd<={sequence_adjusted[38:0],sequence_binary[31]};
                time_bcd<={time_adjusted[38:0],time_binary[31]};
                decimal_busy<=0;
            end
        end
    end

    reg [15:0] tile_entry;
    reg [7:0] glyph;
    reg [1:0] scale_mode, quadrant_x;
    reg quadrant_y;
    reg [3:0] glyph_x;
    reg [4:0] glyph_y;
    reg [2:0] foreground;
    reg [23:0] background;
    reg [2:0] probability_row;
    reg [7:0] probability;
    reg [10:0] probability_width;
    reg [3:0] character;
    reg [2:0] visible_row;
    reg [7:0] winning_probability;
    reg [10:0] dx;
    reg dynamic_row;
    always @* begin
        tile_entry=page_s1?library_q:guide_q;
        glyph=tile_entry[7:0];foreground=tile_entry[10:8];
        scale_mode=tile_entry[12:11];quadrant_x=tile_entry[14:13];quadrant_y=tile_entry[15];
        background=IVORY;
        probability_row=(y_s1-11'd384)>>5;
        probability=percentages_s1[probability_row*8+:8];
        if(probability>100)probability=100;
        probability_width={3'd0,probability}+({3'd0,probability}<<1);
        winning_probability=class_s1<8?percentages_s1[class_s1*8+:8]:0;
        visible_row=(y_s1-11'd448)>>6;
        character=0;dx=0;dynamic_row=0;
        if(x_s1<288)begin
            background=SIDEBAR;
            if(x_s1>=24&&x_s1<264&&((!page_s1&&y_s1>=264&&y_s1<336)||(page_s1&&y_s1>=360&&y_s1<432)))background=24'h36574a;
            if(x_s1>=48&&x_s1<240&&y_s1==560)background=24'h3e5a4d;
        end else begin
            if(y_s1<96)background=24'hfafbf6;
            if(y_s1==95||y_s1==1000)background=24'hdce4d4;
            if(y_s1>=1001)background=24'hfafbf6;
            if(!page_s1)begin
                if(((x_s1>=352&&x_s1<960)||(x_s1>=992&&x_s1<1856))&&y_s1>=304&&y_s1<768)background=24'hffffff;
                if(x_s1>=352&&x_s1<1856&&y_s1>=800&&y_s1<992)background=24'hffffff;
                if(x_s1>=1040&&x_s1<1808&&y_s1>=384&&y_s1<640&&filter_s1<8&&probability_row==filter_s1[2:0])background=24'he8f2e2;
                if(x_s1>=1056&&x_s1<1792&&y_s1==672)background=24'he6ebdf;
                if(x_s1>=1328&&x_s1<1628&&y_s1>=384&&y_s1<640&&y_s1[4:0]>=10&&y_s1[4:0]<22)begin
                    background=24'hecf0e5;
                    if(ready_s1&&x_s1-1328<probability_width)background=class_color(probability_row);
                end
                if(x_s1>=400&&x_s1<1424&&y_s1>=896&&y_s1<944)begin
                    background=x_s1[3:0]<14?24'hecf0e5:24'hffffff;
                    if(rd_valid&&x_s1[3:0]<14)background=class_color(rd_class);
                end
                if(x_s1>=400&&x_s1<1424&&y_s1>=884&&y_s1<892&&rd_valid&&rd_bookmark&&x_s1[3:0]<14)background=INK;
                if(x_s1>=400&&x_s1<912&&y_s1>=416&&y_s1<480)begin
                    dx=x_s1-400;character=dx>>6;
                    glyph=label_glyph(ready_s1?{1'b0,class_s1[2:0]}:4'd8,character);
                    foreground=0;scale_mode=3;quadrant_x=dx[5:4];quadrant_y=(y_s1-11'd416)>>5;
                end
                if(x_s1>=640&&x_s1<768&&y_s1>=512&&y_s1<576)begin
                    dx=x_s1-640;glyph=ready_s1?decimal_glyph(winning_probability,dx[6:5]):GLYPH_DASH;
                    foreground=0;scale_mode=2;quadrant_x={1'b0,dx[4]};quadrant_y=y_s1[5];
                end
                if(x_s1>=640&&x_s1<800&&(y_s1>=640&&y_s1<672||y_s1>=704&&y_s1<736))begin
                    character=(x_s1-640)>>4;
                    glyph=ready_s1?number_glyph(y_s1<672?sequence_bcd:time_bcd,character):GLYPH_DASH;
                    foreground=0;scale_mode=0;quadrant_x=0;quadrant_y=0;
                end
                if(x_s1>=1680&&x_s1<1744&&y_s1>=384&&y_s1<640)begin
                    character=(x_s1-1680)>>4;glyph=ready_s1?decimal_glyph(probability,character[1:0]):GLYPH_DASH;
                    foreground=0;scale_mode=0;quadrant_x=0;quadrant_y=0;
                end
                if(x_s1>=1376&&x_s1<1664&&y_s1>=704&&y_s1<736)begin
                    dx=x_s1-1376;character=dx>>5;
                    glyph=label_glyph(filter_s1<8?filter_s1:4'd11,character);
                    foreground=0;scale_mode=1;quadrant_x={1'b0,dx[4]};quadrant_y=0;
                end
            end else begin
                if(x_s1>=352&&x_s1<1856&&y_s1>=400&&y_s1<976)background=24'hffffff;
                if(x_s1>=352&&x_s1<1856&&y_s1>=400&&y_s1<448)background=24'heaf0e3;
                if(y_s1>=304&&y_s1<368&&x_s1>=chip_left(filter_s1)&&x_s1<chip_right(filter_s1))background=24'hdcebd8;
                if(x_s1>=352&&x_s1<1856&&y_s1>=448&&y_s1<960)begin
                    if(visible_row==selected_s1[2:0]&&rd_valid)begin
                        background=24'he8f2e2;
                        if(x_s1<360)background=24'h548261;
                    end
                    if(y_s1[5:0]==63)background=24'hecf0e5;
                    if(x_s1>=1800&&x_s1<1824&&y_s1[5:0]>=24&&y_s1[5:0]<40&&rd_valid&&rd_bookmark)background=INK;
                    if(y_s1[5:0]>=16&&y_s1[5:0]<48&&rd_valid)begin
                        dynamic_row=1;
                        foreground=0;scale_mode=0;quadrant_x=0;quadrant_y=0;
                        if(x_s1>=384&&x_s1<544)begin
                            character=(x_s1-384)>>4;glyph=number_glyph(sequence_bcd,character);
                        end else if(x_s1>=624&&x_s1<784)begin
                            character=(x_s1-624)>>4;glyph=number_glyph(time_bcd,character);
                        end else if(x_s1>=944&&x_s1<1232)begin
                            dx=x_s1-944;character=dx>>5;glyph=label_glyph({1'b0,rd_class},character);scale_mode=1;quadrant_x={1'b0,dx[4]};
                        end else if(x_s1>=1360&&x_s1<1424)begin
                            character=(x_s1-1360)>>4;glyph=decimal_glyph(rd_confidence,character[1:0]);
                        end else if(x_s1>=1648&&x_s1<1776)begin
                            dx=x_s1-1648;character=dx>>5;glyph=label_glyph(rd_bookmark?4'd9:4'd10,character);scale_mode=1;quadrant_x={1'b0,dx[4]};
                        end
                    end
                end
                if(item_count_s1==0&&x_s1>=1040&&x_s1<1232&&y_s1>=640&&y_s1<672)begin
                    dx=x_s1-1040;glyph=label_glyph(4'd12,dx>>5);foreground=1;scale_mode=1;quadrant_x={1'b0,dx[4]};quadrant_y=0;
                end
            end
        end
        case(scale_mode)
            0:begin glyph_x=x_s1[3:0];glyph_y=y_s1[4:0];end
            1:begin glyph_x={quadrant_x[0],x_s1[3:1]};glyph_y=y_s1[4:0];end
            2:begin glyph_x={quadrant_x[0],x_s1[3:1]};glyph_y={quadrant_y,y_s1[4:1]};end
            default:begin glyph_x={quadrant_x,x_s1[3:2]};glyph_y={quadrant_y,y_s1[4:1]};end
        endcase
        if(dynamic_row)glyph_y={~y_s1[4],y_s1[3:0]};
    end

    reg [15:0] font_q;
    reg [3:0] glyph_x_s2;
    reg [23:0] foreground_s2, background_s2, color_s3, color_s4;
    reg text_s2;
    always @(posedge pix_clk) begin
        guide_q<=guide_rom[tile_address];library_q<=library_rom[tile_address];
        x_s1<=pix_x;y_s1<=pix_y;page_s1<=page_library;ready_s1<=result_ready&&class_idx<8;
        class_s1<=class_idx;percentages_s1<=percentages;selected_s1<=selected_index;
        filter_s1<=filter_class;item_count_s1<=item_count;
        font_q<=font_rom[{glyph,glyph_y}];glyph_x_s2<=glyph_x;
        foreground_s2<=text_color(foreground);background_s2<=background;text_s2<=glyph!=0;
        color_s3<=text_s2&&font_q[15-glyph_x_s2]?foreground_s2:background_s2;
        color_s4<=color_s3;
        rgb<=de_pipe[3]?color_s4:24'd0;
        de_pipe<={de_pipe[3:0],pix_de};hs_pipe<={hs_pipe[3:0],pix_hs};vs_pipe<={vs_pipe[3:0],pix_vs};
        vs_d<=pix_vs;
        if(!rst_pix_n)begin de_pipe<=0;hs_pipe<=0;vs_pipe<=0;vs_d<=0;rgb<=0;end
    end
endmodule
