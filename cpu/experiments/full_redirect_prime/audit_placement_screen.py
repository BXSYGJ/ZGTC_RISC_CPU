import json
import re
from pathlib import Path

from audit_short import ROOT, digest, require
from audit_ila_mapping import SOURCE
from qualify_full_ila import qualify

RUNS = ((1, "20260910-redirect-prime-seed1"),
        (2, "20260910-redirect-prime-seed2-remapped"),
        (3, "20260910-redirect-prime-seed3"))


def audit():
    rows = []
    shared = None
    normalized_configuration = None
    for seed, name in RUNS:
        stage = ROOT / "build/ila" / name
        report = qualify(stage, source=SOURCE, placement_seed=seed)
        stored = json.loads((stage / "physical-qualification.json").read_text(encoding="utf-8"))
        require(stored == report, "Stored physical result differs: " + name)
        inputs = {filename: digest(stage / filename) for filename in
                  ("source.adf", "netlist.v", "firmware.hex", "board.fdc", "uart_remotelab.fdc", "source-snapshot.json")}
        require(shared is None or shared == inputs, "Physical source/firmware/constraints differ across seeds")
        shared = inputs
        fic = (stage / "cpu-remapped.fic").read_text(encoding="utf-8-sig")
        normalized = re.sub(r"(?m)^Project.device.designInputFile=.*$", "Project.device.designInputFile=SOURCE", fic)
        normalized = "\n".join(line for line in normalized.splitlines() if not line.startswith("#Generated by Fabric Inserter "))
        require(normalized_configuration is None or normalized_configuration == normalized, "ILA settings differ across seeds")
        normalized_configuration = normalized
        timing = (stage / "report_timing/pds_soc_top.rtr").read_text(encoding="utf-8-sig")
        starts = re.findall(r"(?m)^Startpoint\s*:\s*(.+)$", timing)
        ends = re.findall(r"(?m)^Endpoint\s*:\s*(.+)$", timing)
        require(starts and ends, "Missing critical path endpoints")
        rows.append({"seed": seed, "run": name, "clock_hz": report["clock_hz"],
                     "post_route_luts": report["resources"]["post_route_luts"],
                     "post_route_ffs": report["resources"]["post_route_ffs"],
                     "setup_wns_ns": report["setup_wns_ns"], "timing_passed": report["physical_timing_passed"],
                     "ila": report["ila"], "critical_startpoint": starts[0].strip(), "critical_endpoint": ends[0].strip(),
                     "physical_receipt_sha256": digest(stage / "physical-qualification.json"),
                     "bitstream_sha256": report["outputs_sha256"]["bitstream"]})
    receipt = {"schema": 1, "scope": "same-source, same-firmware, same-constraint, full-ILA placement comparison",
               "shared_inputs_sha256": shared, "runs": rows, "any_timing_passed": any(row["timing_passed"] for row in rows),
               "hardware_validated": False, "baseline_replaced": False}
    destination = ROOT / "build/placement-comparison.json"
    text = json.dumps(receipt, indent=2) + "\n"
    require(not destination.exists() or destination.read_text(encoding="utf-8") == text, "Refusing to overwrite changed placement comparison")
    destination.write_text(text, encoding="utf-8")
    return receipt


if __name__ == "__main__":
    print(json.dumps(audit(), indent=2))
